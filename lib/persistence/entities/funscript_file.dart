import 'dart:convert';
import 'dart:io';

import 'package:objectbox/objectbox.dart';
import 'package:syncopathy/persistence/entities/media_file.dart';
import 'package:syncopathy/model/json/funscript_metadata.dart';

@Entity()
class FunscriptFile {
  @Id()
  int id = 0;
  String path;

  @Transient()
  FunscriptMetadata? metadata;
  String? get metadataDb =>
      metadata == null ? null : jsonEncode(metadata?.toJson());
  set metadataDb(String? json) => json != null
      ? metadata = FunscriptMetadata.fromJson(jsonDecode(json))
      : metadata = null;

  @Index(type: IndexType.value)
  @Unique(onConflict: ConflictStrategy.fail)
  String funscriptHash;

  int algorithmVersion = 0;

  double averageSpeed;
  double averageMin;
  double averageMax;

  bool isScriptToken;
  bool fileNotFound;

  @Property(type: PropertyType.date)
  DateTime? firstIndexedOn;

  @Backlink('funscripts')
  final media = ToMany<MediaFile>();

  FunscriptFile({
    required this.path,
    required this.averageSpeed,
    required this.averageMin,
    required this.averageMax,
    required this.isScriptToken,
    required this.fileNotFound,
    required this.funscriptHash,
    this.metadata,
  });

  String get fileName => path.split(Platform.pathSeparator).last;

  /// Whether this script advertises itself as machine-generated.
  ///
  /// There is no standard marker for it, so both the tags and the `creator`
  /// field are matched against normalized sets: generators variously tag their
  /// output, or leave it untagged and only name the tool that produced it.
  /// Metadata is decoded once when the entity loads, so this is a string scan
  /// over a handful of tags rather than a database read.
  bool get isAiGenerated {
    final meta = metadata;
    if (meta == null) return false;
    for (final tag in meta.tags) {
      if (_aiTags.contains(_normalizeProvenanceToken(tag))) return true;
    }
    final creator = meta.creator;
    if (creator == null) return false;
    final normalized = _normalizeProvenanceToken(creator);
    return _aiCreators.contains(normalized) || _aiTags.contains(normalized);
  }

  /// Copies the computed metrics and metadata from [source] onto this instance.
  /// Used when relocating a funscript to a file whose analysis lives elsewhere,
  /// without replacing this entity (and its DB id / relations).
  void applyMetricsFrom(FunscriptFile source) {
    averageSpeed = source.averageSpeed;
    averageMin = source.averageMin;
    averageMax = source.averageMax;
    isScriptToken = source.isScriptToken;
    metadata = source.metadata;
  }
}

/// Normalizes a tag or creator string for matching: generators spell the same
/// marker as `ai-generated`, `AI Generated`, `ai_generated` or `aigenerated`,
/// and identify tools as `funscript.io` or `FunScript IO`.
String _normalizeProvenanceToken(String value) =>
    value.toLowerCase().replaceAll(RegExp(r'[-_\s.]'), '');

/// Tag values that mark a script as machine-generated.
const Set<String> _aiTags = {
  'ai',
  'aigenerated',
  'aiscript',
  'generated',
  'autogenerated',
  'automated',
  'machinegenerated',
  'motiontracking',
};

/// Tools that generate scripts, matched against the metadata `creator` field.
/// Many generated scripts carry no tag at all and only name the tool here.
const Set<String> _aiCreators = {'fungen', 'scriptaxis', 'funscriptio', 'mtfg'};

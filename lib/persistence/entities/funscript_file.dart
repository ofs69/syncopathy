import 'dart:convert';
import 'dart:io';

import 'package:objectbox/objectbox.dart';
import 'package:syncopathy/persistence/entities/media_file.dart';
import 'package:syncopathy/model/json/funscript_metadata.dart';

@Entity()
class FunscriptFile {
  @Id()
  int id = 0;
  String path;

  @Transient()
  FunscriptMetadata? metadata;
  String? get metadataDb =>
      metadata == null ? null : jsonEncode(metadata?.toJson());
  set metadataDb(String? json) => json != null
      ? metadata = FunscriptMetadata.fromJson(jsonDecode(json))
      : metadata = null;

  @Index(type: IndexType.value)
  @Unique(onConflict: ConflictStrategy.fail)
  String funscriptHash;

  int algorithmVersion = 0;

  double averageSpeed;
  double averageMin;
  double averageMax;

  bool isScriptToken;
  bool fileNotFound;

  @Property(type: PropertyType.date)
  DateTime? firstIndexedOn;

  @Backlink('funscripts')
  final media = ToMany<MediaFile>();

  FunscriptFile({
    required this.path,
    required this.averageSpeed,
    required this.averageMin,
    required this.averageMax,
    required this.isScriptToken,
    required this.fileNotFound,
    required this.funscriptHash,
    this.metadata,
  });

  String get fileName => path.split(Platform.pathSeparator).last;

  /// Whether this script advertises itself as machine-generated.
  ///
  /// There is no standard marker for it, so both the tags and the `creator`
  /// field are matched against normalized sets: generators variously tag their
  /// output, or leave it untagged and only name the tool that produced it.
  /// Metadata is decoded once when the entity loads, so this is a string scan
  /// over a handful of tags rather than a database read.
  bool get isAiGenerated {
    final meta = metadata;
    if (meta == null) return false;
    for (final tag in meta.tags) {
      if (_aiTags.contains(_normalizeProvenanceToken(tag))) return true;
    }
    final creator = meta.creator;
    if (creator == null) return false;
    final normalized = _normalizeProvenanceToken(creator);
    return _aiCreators.contains(normalized) || _aiTags.contains(normalized);
  }

  /// Copies the computed metrics and metadata from [source] onto this instance.
  /// Used when relocating a funscript to a file whose analysis lives elsewhere,
  /// without replacing this entity (and its DB id / relations).
  void applyMetricsFrom(FunscriptFile source) {
    averageSpeed = source.averageSpeed;
    averageMin = source.averageMin;
    averageMax = source.averageMax;
    isScriptToken = source.isScriptToken;
    metadata = source.metadata;
  }
}

/// Normalizes a tag or creator string for matching: generators spell the same
/// marker as `ai-generated`, `AI Generated`, `ai_generated` or `aigenerated`,
/// and identify tools as `funscript.io` or `FunScript IO`.
String _normalizeProvenanceToken(String value) =>
    value.toLowerCase().replaceAll(RegExp(r'[-_\s.]'), '');

/// Tag values that mark a script as machine-generated.
const Set<String> _aiTags = {
  'ai',
  'aigenerated',
  'aiscript',
  'generated',
  'autogenerated',
  'automated',
  'machinegenerated',
  'motiontracking',
};

/// Tools that generate scripts, matched against the metadata `creator` field.
/// Many generated scripts carry no tag at all and only name the tool here.
const Set<String> _aiCreators = {'fungen', 'scriptaxis', 'funscriptio', 'mtfg'};

/// Multi-axis funscripts sit next to the stroke script and share its basename,
/// distinguished only by a suffix naming the axis they drive
/// (`scene.twist.funscript`, `scene_R1.funscript`). They are useless on their
/// own — a twist track played as a stroke track is noise — so they must never
/// be picked as a media's main script while a stroke script is available.
///
/// Returns a rank for [path]: lower is a better main-script candidate.
/// 0 = no axis suffix at all (the plain `scene.funscript`), 1 = explicitly
/// named as the stroke axis (`L0`/`stroke`), 2 = a secondary axis. An
/// unrecognized suffix ranks 0: names like `scene.part2.funscript` are ordinary
/// scripts, and only known axis tokens are demoted.
int funscriptAxisRank(String path) {
  final name = path.split('/').last.split(r'\').last;
  final base = name.toLowerCase().endsWith('.funscript')
      ? name.substring(0, name.length - '.funscript'.length)
      : name;

  final match = _axisSuffixPattern.firstMatch(base);
  if (match == null) return 0;

  final token = match.group(1)!.toLowerCase();
  if (_strokeAxisTokens.contains(token)) return 1;
  if (_secondaryAxisTokens.contains(token)) return 2;
  return 0;
}

/// Strips a recognized axis suffix from [basename] (a filename with no
/// extension), returning the stem shared by every script of one multi-axis set.
///
/// `scene.twist` and `scene_L0` both reduce to `scene`, which is what groups a
/// stroke script with its companions. A name with no recognized axis token is
/// returned unchanged, so `scene.part2` keeps its suffix.
String stripFunscriptAxisSuffix(String basename) {
  final match = _axisSuffixPattern.firstMatch(basename);
  if (match == null) return basename;

  final token = match.group(1)!.toLowerCase();
  if (_strokeAxisTokens.contains(token) ||
      _secondaryAxisTokens.contains(token)) {
    return basename.substring(0, match.start);
  }
  return basename;
}

final RegExp _axisSuffixPattern = RegExp(r'[._\- ]([a-zA-Z]\d|[a-zA-Z]+)$');

/// Suffixes that name the stroke axis itself. Such a script is a perfectly good
/// main script — it just loses to an unsuffixed one when both exist.
const Set<String> _strokeAxisTokens = {'l0', 'stroke'};

/// Suffixes naming an axis other than stroke, in both the T-code channel form
/// used by MultiFunPlayer (`L1`, `R0`, `V0`, …) and the descriptive form
/// written by scripters.
const Set<String> _secondaryAxisTokens = {
  'l1',
  'surge',
  'l2',
  'sway',
  'l3',
  'r0',
  'twist',
  'r1',
  'roll',
  'r2',
  'pitch',
  'v0',
  'vib',
  'vibrate',
  'v1',
  'pump',
  'v2',
  'a0',
  'valve',
  'a1',
  'suck',
  'suction',
  'a2',
  'lube',
};

/// Picks the best main-script candidate from [candidates], or `null` when it is
/// empty. Preference order: a script whose file is present, then a stroke
/// script over a secondary-axis one, then real actions over a script token.
/// Ties keep the order [candidates] came in.
FunscriptFile? pickMainFunscript(Iterable<FunscriptFile> candidates) {
  FunscriptFile? best;
  List<int>? bestKey;

  for (final candidate in candidates) {
    final key = [
      candidate.fileNotFound ? 1 : 0,
      funscriptAxisRank(candidate.path),
      candidate.isScriptToken ? 1 : 0,
    ];
    if (bestKey == null || _isBetter(key, bestKey)) {
      best = candidate;
      bestKey = key;
    }
  }

  return best;
}

bool _isBetter(List<int> a, List<int> b) {
  for (var i = 0; i < a.length; i++) {
    if (a[i] != b[i]) return a[i] < b[i];
  }
  return false;
}

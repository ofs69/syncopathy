import 'package:flutter_test/flutter_test.dart';
import 'package:syncopathy/media_library/media_badge.dart';
import 'package:syncopathy/model/json/funscript_metadata.dart';
import 'package:syncopathy/model/json/media_library_settings.dart';
import 'package:syncopathy/persistence/entities/funscript_file.dart';
import 'package:syncopathy/persistence/entities/media_file.dart';

FunscriptFile _funscript({
  List<String> tags = const [],
  String? creator,
  bool withMetadata = true,
}) {
  return FunscriptFile(
    path: r'C:\scripts\clip.funscript',
    averageSpeed: 120,
    averageMin: 10,
    averageMax: 90,
    isScriptToken: false,
    fileNotFound: false,
    funscriptHash: 'hash',
    metadata: withMetadata
        ? FunscriptMetadata(tags: tags, creator: creator)
        : null,
  );
}

MediaFile _media() => MediaFile(
  name: 'clip',
  mediaPath: r'C:\media\clip.mp4',
  fileHash: 'media-hash',
  playCount: 0,
  fileNotFound: false,
);

void main() {
  group('FunscriptFile.isAiGenerated', () {
    test('matches AI tags regardless of separators and case', () {
      for (final tag in [
        'ai',
        'AI',
        'ai-generated',
        'AI Generated',
        'ai_generated',
        'aigenerated',
        'autogenerated',
        'motion tracking',
      ]) {
        expect(
          _funscript(tags: [tag]).isAiGenerated,
          isTrue,
          reason: 'tag "$tag" should be recognised',
        );
      }
    });

    test('matches a known generator named only in creator', () {
      expect(_funscript(creator: 'FunGen').isAiGenerated, isTrue);
      expect(_funscript(creator: 'funscript.io').isAiGenerated, isTrue);
      // A creator that spells the marker itself, with no tag at all.
      expect(_funscript(creator: 'AI Generated').isAiGenerated, isTrue);
    });

    test('leaves hand-made scripts alone', () {
      expect(_funscript(tags: ['hardcore', 'pov']).isAiGenerated, isFalse);
      expect(_funscript(creator: 'SomeHumanScripter').isAiGenerated, isFalse);
      expect(_funscript(withMetadata: false).isAiGenerated, isFalse);
    });

    test('does not match tags that merely contain "ai"', () {
      expect(_funscript(tags: ['maid', 'trailer']).isAiGenerated, isFalse);
    });
  });

  group('badge registry', () {
    test('resolveBadges returns registry order, not the enabled order', () {
      final resolved = resolveBadges(['aiGenerated', 'duration']);
      expect(resolved.map((s) => s.id), ['duration', 'aiGenerated']);
    });

    test('resolveBadges drops ids with no registered badge', () {
      final resolved = resolveBadges(['duration', 'badgeFromTheFuture']);
      expect(resolved.map((s) => s.id), ['duration']);
    });

    test('every badge has a unique id and is reachable by id', () {
      final ids = availableBadges.map((s) => s.id).toList();
      expect(ids.toSet(), hasLength(ids.length));
      expect(badgesById.keys, containsAll(ids));
    });

    test('script count badge hides until there is more than one script', () {
      final spec = badgesById['funscriptCount']!;
      final media = _media();
      expect(spec.build(media), isNull);

      media.funscripts.add(_funscript());
      expect(spec.build(media), isNull);

      media.funscripts.add(_funscript());
      expect(spec.build(media)?.text, '2');
    });

    test('AI badge hides unless the main script is generated', () {
      final spec = badgesById['aiGenerated']!;
      final media = _media();
      final human = _funscript(tags: ['pov']);
      media.funscripts.add(human);
      media.mainFunscript.target = human;
      expect(spec.build(media), isNull);

      final generated = _funscript(tags: ['ai-generated']);
      media.mainFunscript.target = generated;
      expect(spec.build(media)?.tooltip, 'AI-generated script');
      // Icon-only: a provenance marker carries no measurement.
      expect(spec.build(media)?.text, isNull);
    });
  });

  group('MediaLibrarySettings badge migration', () {
    test('seeds badges from the legacy show* toggles', () {
      final settings = MediaLibrarySettings.fromJson({
        'showDuration': true,
        'showPlayCount': false,
        'showAverageSpeed': true,
        'showAverageMinMax': false,
      });
      expect(settings.enabledBadges, contains('duration'));
      expect(settings.enabledBadges, contains('averageSpeed'));
      expect(settings.enabledBadges, isNot(contains('playCount')));
      expect(settings.enabledBadges, isNot(contains('averageMinMax')));
    });

    test('badges with no legacy toggle fall back to their own default', () {
      final settings = MediaLibrarySettings.fromJson({'showDuration': false});
      // Absent legacy keys must not read as "off".
      expect(settings.enabledBadges, contains('playCount'));
      expect(settings.enabledBadges, contains('funscriptCount'));
      expect(settings.enabledBadges, contains('aiGenerated'));
      expect(settings.enabledBadges, isNot(contains('duration')));
    });

    test('a stored badge list wins over the legacy toggles', () {
      final settings = MediaLibrarySettings.fromJson({
        'showDuration': true,
        'enabledBadges': ['aiGenerated'],
      });
      expect(settings.enabledBadges, ['aiGenerated']);
    });

    test('an empty stored list is preserved, not treated as unset', () {
      final settings = MediaLibrarySettings.fromJson({'enabledBadges': []});
      expect(settings.enabledBadges, isEmpty);
    });

    test('unknown badge ids are dropped on load', () {
      final settings = MediaLibrarySettings.fromJson({
        'enabledBadges': ['duration', 'badgeFromTheFuture'],
      });
      expect(settings.enabledBadges, ['duration']);
    });

    test('round trips through json', () {
      final settings = MediaLibrarySettings(enabledBadges: ['duration', 'ai']);
      final restored = MediaLibrarySettings.fromJson(settings.toJson());
      // 'ai' is not a badge id, so only the real one survives.
      expect(restored.enabledBadges, ['duration']);
    });

    test('a fresh install gets the default badge set', () {
      expect(MediaLibrarySettings().enabledBadges, defaultBadgeIds);
      expect(defaultBadgeIds, isNotEmpty);
    });
  });
}
